#!/usr/bin/env python3
"""Builds the French page and the search metadata from the English page.

index.html is the English source and i18n/fr.json holds the French text. Run
`python3 build.py` after editing either one. It rewrites:

  - fr/index.html: the full French page, so search engines index French as
    its own URL instead of text swapped in by JavaScript;
  - the JSON-LD block in both pages (site, game and FAQ data), with the FAQ
    read from the visible page so the two never disagree;
  - sitemap.xml, listing both languages as alternates of each other.

Standard library only, so it runs anywhere Python 3 does.
"""
import datetime
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = 'https://sanandreasonline.com'
TODAY = datetime.date.today().isoformat()
FIRST_RELEASE = '2026-08-02'
I18N_TAGS = r'(?:p|h2|h3|span|summary|a|button|strong|li)'


def read(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as f:
        return f.read()


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8') as f:
        f.write(text)


def sub_one(pattern, repl, text, flags=0):
    new, count = re.subn(pattern, repl, text, count=1, flags=flags)
    if count != 1:
        raise SystemExit(f'build.py: pattern not found: {pattern}')
    return new


def meta(text, attr, name):
    return re.search(rf'<meta {attr}="{re.escape(name)}" content="([^"]*)">', text).group(1)


def faq_entries(page):
    """The visible FAQ as (question, answer) pairs, tags stripped."""
    pairs = re.findall(r'<details[^>]*>\s*<summary[^>]*>(.*?)</summary>\s*<p[^>]*>(.*?)</p>', page, re.S)
    clean = lambda s: html.unescape(re.sub(r'<[^>]+>', '', s)).strip()
    return [(clean(q), clean(a)) for q, a in pairs]


def json_ld(page, lang):
    url = SITE + ('/fr/' if lang == 'fr' else '/')
    description = html.unescape(meta(page, 'name', 'description'))
    data = [
        {'@context': 'https://schema.org', '@type': 'WebSite', 'name': 'San Andreas Online',
         'alternateName': 'SA:O', 'url': SITE + '/', 'inLanguage': ['en', 'fr']},
        {'@context': 'https://schema.org', '@type': ['VideoGame', 'SoftwareApplication'],
         'name': 'San Andreas Online', 'alternateName': ['SA:O', 'San Andreas Online multiplayer'],
         'description': description, 'url': url, 'inLanguage': lang,
         'image': SITE + '/og.jpg?v=2', 'applicationCategory': 'GameApplication',
         'operatingSystem': 'Windows', 'gamePlatform': 'PC', 'playMode': 'MultiPlayer',
         'genre': ['Open world', 'Multiplayer', 'Action'],
         'datePublished': FIRST_RELEASE, 'dateModified': TODAY,
         'author': {'@type': 'Person', 'name': 'Dryxio', 'url': 'https://github.com/Dryxio'},
         'isBasedOn': {'@type': 'SoftwareApplication', 'name': 'Multi Theft Auto: San Andreas',
                       'url': 'https://multitheftauto.com'},
         'downloadUrl': SITE + '/download', 'isAccessibleForFree': True,
         'license': 'https://www.gnu.org/licenses/gpl-3.0.html',
         'offers': {'@type': 'Offer', 'price': '0', 'priceCurrency': 'USD'},
         'sameAs': ['https://github.com/Dryxio/san-andreas-online', 'https://discord.com/invite/mgFRd2AzF8']},
        {'@context': 'https://schema.org', '@type': 'FAQPage', 'inLanguage': lang, 'mainEntity': [
            {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': a}}
            for q, a in faq_entries(page)]},
    ]
    block = json.dumps(data, ensure_ascii=False, indent=1).replace('</', '<\\/')
    return f'  <!-- LD:start (generated by build.py) -->\n  <script type="application/ld+json">\n{block}\n  </script>\n  <!-- LD:end -->'


def with_ld(page, lang):
    return sub_one(r'  <!-- LD:start.*?<!-- LD:end -->', lambda _: json_ld(page, lang), page, re.S)


def french(page, fr):
    # The closing tag must match the opening one, so a paragraph that contains
    # a link is replaced whole instead of stopping at the link's </a>.
    def text(match):
        key = match.group(3)
        if key not in fr:
            raise SystemExit(f'build.py: i18n/fr.json has no "{key}"')
        return match.group(1) + fr[key] + match.group(4)

    page = re.sub(rf'(<({I18N_TAGS})\b[^>]*\bdata-i18n="([^"]+)"[^>]*>).*?(</\2>)', text, page, flags=re.S)

    def alt(match):
        key = match.group(2)
        if key not in fr:
            raise SystemExit(f'build.py: i18n/fr.json has no "{key}"')
        return f'alt="{html.escape(fr[key], quote=True)}" data-i18n-alt="{key}"'
    page = re.sub(r'alt="([^"]*)" data-i18n-alt="([^"]+)"', alt, page)

    attr = lambda s: html.escape(s, quote=True)
    page = sub_one(r'<html lang="en">', '<html lang="fr">', page)
    page = sub_one(r'<title>.*?</title>', lambda _: f'<title>{attr(fr["head.title"])}</title>', page)
    for kind, name, key in [('name', 'description', 'head.desc'), ('property', 'og:title', 'head.ogtitle'),
                            ('property', 'og:description', 'head.ogdesc'), ('name', 'twitter:title', 'head.ogtitle'),
                            ('name', 'twitter:description', 'head.ogdesc'), ('property', 'og:image:alt', 'head.ogalt')]:
        page = sub_one(rf'<meta {kind}="{re.escape(name)}" content="[^"]*">',
                       lambda _, k=kind, n=name, v=fr[key]: f'<meta {k}="{n}" content="{attr(v)}">', page)
    page = sub_one(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{SITE}/fr/">', page)
    page = sub_one(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{SITE}/fr/">', page)
    page = sub_one(r'<meta property="og:locale" content="en_US">\n  <meta property="og:locale:alternate" content="fr_FR">',
                   '<meta property="og:locale" content="fr_FR">\n  <meta property="og:locale:alternate" content="en_US">', page)
    page = sub_one(r'<a class="lang"[^>]*>FR</a>',
                   '<a class="lang" id="lang" href="/" hreflang="en" lang="en" data-lang-switch="en" aria-label="English version">EN</a>', page)
    page = sub_one(r'aria-label="San Andreas Online home"', 'aria-label="Accueil San Andreas Online"', page)
    return page


def sitemap():
    alternates = (f'    <xhtml:link rel="alternate" hreflang="en" href="{SITE}/"/>\n'
                  f'    <xhtml:link rel="alternate" hreflang="fr" href="{SITE}/fr/"/>\n'
                  f'    <xhtml:link rel="alternate" hreflang="x-default" href="{SITE}/"/>\n')
    urls = ''.join(f'  <url>\n    <loc>{SITE}{path}</loc>\n    <lastmod>{TODAY}</lastmod>\n{alternates}  </url>\n'
                   for path in ('/', '/fr/'))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
            f'{urls}</urlset>\n')


def main():
    english = read('index.html')
    fr = json.loads(read('i18n/fr.json'))
    write('index.html', with_ld(english, 'en'))
    write('fr/index.html', with_ld(french(english, fr), 'fr'))
    write('sitemap.xml', sitemap())
    print('built index.html, fr/index.html and sitemap.xml')


if __name__ == '__main__':
    main()
