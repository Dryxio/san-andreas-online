namespace {
using Clock = std::chrono::steady_clock;
enum class Stage { JoinData, Admitting, InGameNotice, InitialData, Playing };
struct Session {
    GamePeer peer;
    std::string serial;
    Stage stage = Stage::JoinData;
    Clock::time_point since = Clock::now();
    bool closed = false;
};

// Gameplay frames may only invoke handlers for client application packets.
// Stock network notifications are generated by the stock module itself.
bool AllowedInGame(unsigned char kind)
{
    switch (kind) {
        case PACKET_ID_RPC: case PACKET_ID_LATENT_TRANSFER:
        case PACKET_ID_PED_WASTED: case PACKET_ID_PLAYER_WASTED:
        case PACKET_ID_PLAYER_PURESYNC: case PACKET_ID_PLAYER_VEHICLE_PURESYNC:
        case PACKET_ID_PLAYER_KEYSYNC: case PACKET_ID_PLAYER_BULLETSYNC:
        case PACKET_ID_PED_TASK: case PACKET_ID_WEAPON_BULLETSYNC:
        case PACKET_ID_DETONATE_SATCHELS: case PACKET_ID_DESTROY_SATCHELS:
        case PACKET_ID_COMMAND: case PACKET_ID_EXPLOSION: case PACKET_ID_PROJECTILE:
        case PACKET_ID_VEHICLE_INOUT: case PACKET_ID_VEHICLE_DAMAGE_SYNC:
        case PACKET_ID_VEHICLE_TRAILER: case PACKET_ID_VOICE_DATA: case PACKET_ID_VOICE_END:
        case PACKET_ID_UNOCCUPIED_VEHICLE_SYNC: case PACKET_ID_PED_SYNC:
        case PACKET_ID_LUA_EVENT: case PACKET_ID_CUSTOM_DATA: case PACKET_ID_CAMERA_SYNC:
        case PACKET_ID_OBJECT_SYNC: case PACKET_ID_VEHICLE_PUSH_SYNC:
        case PACKET_ID_PLAYER_RESOURCE_START: case PACKET_ID_PLAYER_WORLD_SPECIAL_PROPERTY:
            return true;
        default: return false;
    }
}
bool AllowFrame(Session& session, CPlayer* player, uint8_t kind, uint32_t bits, const uint8_t* data)
{
    if (player && (player->IsLeavingServer() || player->IsBeingDeleted())) return false;
    switch (session.stage) {
        case Stage::JoinData:
            if (player || kind != PACKET_ID_PLAYER_JOINDATA || bits > 8192 * 8) return false;
            session.stage = Stage::Admitting;
            return true;
        case Stage::InGameNotice:
            return player && kind == PACKET_ID_RPC && bits == 8 && data[0] == CRPCFunctions::PLAYER_INGAME_NOTICE;
        case Stage::InitialData:
            if (!player || kind != PACKET_ID_RPC || bits != 8 || data[0] != CRPCFunctions::INITIAL_DATA_STREAM) return false;
            session.stage = Stage::Playing;
            return true;
        case Stage::Playing:
            return player && player->IsJoined() && AllowedInGame(kind) &&
                   (kind != PACKET_ID_RPC || (bits >= 8 && data[0] != CRPCFunctions::PLAYER_INGAME_NOTICE && data[0] != CRPCFunctions::INITIAL_DATA_STREAM));
        default: return false;
    }
}
}

struct CQuicGameplay::Impl {
    uint64_t (*listen)(const char*,const char*,const char*,const char*,const char*,char*,int) = nullptr;
    void (*stop)(uint64_t) = nullptr;
    uint64_t (*accept)(uint64_t) = nullptr;
    int (*info)(uint64_t,uint8_t*,uint8_t*,uint16_t*) = nullptr;
    int (*poll)(uint64_t,uint8_t*,uint32_t*,uint8_t*,int) = nullptr;
    int (*send)(uint64_t,uint8_t,uint32_t,const uint8_t*,uint8_t,uint8_t) = nullptr;
    void (*close)(uint64_t) = nullptr;
    uint64_t listener = 0;
    std::thread worker;
    std::mutex mutex;
    std::deque<uint64_t> pending;
    std::map<uint64_t, Session> sessions;
    std::vector<uint8_t> buffer;
};

CQuicGameplay::CQuicGameplay() = default;
CQuicGameplay::~CQuicGameplay() { Stop(); }

bool CQuicGameplay::Start(CMainConfig& config)
{
    if (config.m_quicAddress.empty()) return true;
    auto mod = g_pServerInterface->GetModManager();
    // A c-shared Go runtime stays loaded for the process lifetime, including
    // between restarts of the deathmatch module.
#ifdef WIN32
    const auto path = mod->GetAbsolutePath("neon_gameplay.dll");
#else
    const auto path = mod->GetAbsolutePath("libneon_gameplay.so");
#endif
    static auto* library = new CDynamicLibrary();
    if (!library->IsLoaded() && !library->Load(path.c_str())) return false;
    auto impl = std::make_unique<Impl>();
#define LOAD(member, symbol) impl->member = reinterpret_cast<decltype(impl->member)>(library->GetProcedureAddress(symbol)); if (!impl->member) return false
    LOAD(listen, "NeonGameListen");
    LOAD(stop, "NeonGameStopListen");
    LOAD(accept, "NeonGameAccept");
    LOAD(info, "NeonGamePeerInfo");
    LOAD(poll, "NeonGamePoll");
    LOAD(send, "NeonGameSend");
    LOAD(close, "NeonGameClose");
#undef LOAD
    std::array<char, 512> error{};
    auto ca = config.m_quicClientCA.empty() ? SString() : mod->GetAbsolutePath(config.m_quicClientCA.c_str());
    impl->listener = impl->listen(config.m_quicAddress.c_str(), mod->GetAbsolutePath("quic-server.pem").c_str(),
                                  mod->GetAbsolutePath("quic-server.key").c_str(), ca.c_str(), config.GetFileName().c_str(),
                                  error.data(), error.size());
    if (!impl->listener) {
        CLogger::ErrorPrintf("QUIC gameplay listener: %s\n", error.data());
        return false;
    }
    m_impl = std::move(impl);
    m_impl->buffer.resize(256 << 10);
    auto& net = *m_impl;
    net.worker = std::thread([&net] {
        while (auto handle = net.accept(net.listener)) {
            std::lock_guard<std::mutex> lock(net.mutex);
            if (net.pending.size() < 32) net.pending.push_back(handle);
            else net.close(handle);
        }
    });
    CLogger::LogPrintf("QUIC gameplay listening on %s\n", config.m_quicAddress.c_str());
    return true;
}

void CQuicGameplay::Stop()
{
    if (!m_impl) return;
    auto& net = *m_impl;
    net.stop(net.listener);
    if (net.worker.joinable()) net.worker.join();
    for (auto handle : net.pending) net.close(handle);
    for (const auto& entry : net.sessions) net.close(entry.first);
    m_impl.reset();
}

std::string CQuicGameplay::InstallSerial(const GamePeer& peer) const
{
    if (!m_impl) return {};
    auto it = m_impl->sessions.find(peer.Handle());
    return it == m_impl->sessions.end() ? std::string() : it->second.serial;
}

void CQuicGameplay::Close(const GamePeer& peer)
{
    if (!m_impl) return;
    auto it = m_impl->sessions.find(peer.Handle());
    if (it != m_impl->sessions.end()) it->second.closed = true;
}

bool CQuicGameplay::Send(const GamePeer& peer, unsigned char kind, NetBitStreamInterface& stream,
                         NetServerPacketReliability reliability, ePacketOrdering ordering)
{
    if (!m_impl) return false;
    auto it = m_impl->sessions.find(peer.Handle());
    if (it == m_impl->sessions.end() || it->second.closed) return false;
    int mode = reliability == PACKET_RELIABILITY_UNRELIABLE ? 1 : reliability == PACKET_RELIABILITY_UNRELIABLE_SEQUENCED ? 2 : 0;
    if (m_impl->send(peer.Handle(), kind, stream.GetNumberOfBitsUsed(), stream.GetData(), mode, ordering) != 1) return false;
    auto& stage = it->second.stage;
    if (kind == PACKET_ID_SERVER_JOIN_COMPLETE && stage == Stage::Admitting) stage = Stage::InGameNotice;
    if (kind == PACKET_ID_SERVER_JOINEDGAME && stage == Stage::InGameNotice) stage = Stage::InitialData;
    return true;
}

void CQuicGameplay::Pulse()
{
    if (!m_impl) return;
    auto& net = *m_impl;
    std::deque<uint64_t> accepted;
    {
        std::lock_guard<std::mutex> lock(net.mutex);
        accepted.swap(net.pending);
    }
    auto* players = g_pGame->GetPlayerManager();
    auto maxPlayers = g_pGame->GetConfig()->GetMaxPlayers();
    for (auto id : accepted) {
        std::array<uint8_t, 32> hash{};
        uint32_t address = 0;
        uint16_t port = 0;
        if (players->Count() >= maxPlayers || net.sessions.size() >= maxPlayers ||
            !net.info(id, reinterpret_cast<uint8_t*>(&address), hash.data(), &port)) {
            net.close(id);
            continue;
        }
        std::string serial;
        serial.reserve(32);
        constexpr char hex[] = "0123456789ABCDEF";
        for (size_t i = 0; i < 32; ++i) serial += hex[(hash[i/2] >> ((i % 2) ? 0 : 4)) & 15];
        auto it = net.sessions.emplace(id, Session{GamePeer::Quic(id, address, port), serial}).first;
        // A connection event generated locally after TLS starts mod negotiation.
        g_pGame->Packet_PlayerJoin(it->second.peer);
    }
    for (auto it = net.sessions.begin(); it != net.sessions.end();) {
        auto& session = it->second;
        if (session.stage != Stage::Playing && Clock::now() - session.since > std::chrono::seconds(30)) session.closed = true;
        for (unsigned i = 0; !session.closed && i < 32; ++i) {
            uint8_t kind = 0;
            uint32_t bits = 0;
            int result = net.poll(it->first, &kind, &bits, net.buffer.data(), net.buffer.size());
            if (result == 0) break;
            auto* player = players->Get(session.peer);
            // Android begins disposable on-foot sync after SERVER_JOIN_COMPLETE.
            // Datagrams may arrive before either of the ordered join RPCs.
            if (result > 0 && kind == PACKET_ID_PLAYER_PURESYNC &&
                (session.stage == Stage::InGameNotice || session.stage == Stage::InitialData)) continue;
            if (result < 0 || !AllowFrame(session, player, kind, bits, net.buffer.data())) {
                if (result > 0)
                    CLogger::LogPrintf("QUIC: rejected packet %u (%u bits) at admission stage %d\n",
                                       kind, bits, static_cast<int>(session.stage));
                session.closed = true;
                break;
            }
            auto stream = g_pNetServer->AllocateNetServerBitStream(player ? player->GetBitStreamVersion() : 0);
            if (!stream) { session.closed = true; break; }
            // Frame bytes retain their wire alignment. WriteBits right-aligns
            // the final partial byte, so copy that tail one wire bit at a time.
            unsigned bytes = bits / 8;
            if (bytes) stream->Write(reinterpret_cast<const char*>(net.buffer.data()), bytes);
            for (unsigned bit = 0; bit < bits % 8; ++bit) stream->WriteBit((net.buffer[bytes] & (0x80 >> bit)) != 0);
            stream->ResetReadPointer();
            if (!g_pGame->ProcessGamePacket(kind, session.peer, stream, nullptr)) session.closed = true;
            g_pNetServer->DeallocateNetServerBitStream(stream);
        }
        if (!session.closed) { ++it; continue; }
        if (auto* player = players->Get(session.peer)) {
            if (!player->IsLeavingServer() && !player->IsBeingDeleted()) g_pGame->QuitPlayer(*player, CClient::QUIT_TIMEOUT);
        }
        net.close(it->first);
        it = net.sessions.erase(it);
    }
}
